import { StudyPlanner } from "./StudyPlanner";
import { useState } from "react";
import type { Workspace } from "@recall/domain";
import { studyCalendar, studyStatistics } from "@recall/application";
import {
  Select,
  SelectContent,
  SelectItem,
  SelectTrigger,
  SelectValue,
} from "@recall/ui-web/components/select";
import {
  Accordion,
  AccordionContent,
  AccordionItem,
  AccordionTrigger,
} from "@recall/ui-web/components/accordion";

export function StudyStatisticsPanel({
  workspace,
  now,
}: {
  readonly workspace: Workspace;
  readonly now: number;
}) {
  const [scope, setScope] = useState("all");
  const [days, setDays] = useState("30");
  const stats = studyStatistics(
    workspace,
    now,
    studyCalendar(now, Number(days), 30),
    scope === "all" ? undefined : scope,
  );
  return (
    <section className="mt-6 grid gap-5 border-t pt-5" aria-label="Detailed study statistics">
      <h2 className="text-xl font-semibold">Study statistics</h2>
      <StudyPlanner workspace={workspace} now={now} areaId={scope === "all" ? undefined : scope} />
      <div className="flex flex-wrap gap-3">
        <Select value={scope} onValueChange={setScope}>
          <SelectTrigger aria-label="Statistics subject">
            <SelectValue />
          </SelectTrigger>
          <SelectContent>
            <SelectItem value="all">All subjects</SelectItem>
            {workspace.areas.map((area) => (
              <SelectItem key={area.id} value={area.id}>
                {area.title}
              </SelectItem>
            ))}
          </SelectContent>
        </Select>
        <Select value={days} onValueChange={setDays}>
          <SelectTrigger aria-label="Statistics history">
            <SelectValue />
          </SelectTrigger>
          <SelectContent>
            {[7, 30, 90, 365].map((value) => (
              <SelectItem key={value} value={String(value)}>
                Last {value} days
              </SelectItem>
            ))}
          </SelectContent>
        </Select>
      </div>
      <dl className="grid grid-cols-2 gap-4 sm:grid-cols-4">
        {[
          {
            name: "True retention",
            value:
              stats.trueRetention === null
                ? "No data"
                : `${(stats.trueRetention * 100).toFixed(1)}%`,
          },
          { name: "Estimated remembered", value: stats.estimatedRemembered.toFixed(1) },
          { name: "Average daily load", value: stats.dailyLoad.toFixed(1) },
          {
            name: "Recorded study time",
            value: stats.timedReviews
              ? `${(stats.elapsedMs / 60_000).toFixed(1)} min`
              : "No timing data",
          },
        ].map((item) => (
          <div key={item.name}>
            <dt className="text-sm text-muted-foreground">{item.name}</dt>
            <dd className="text-xl font-semibold">{item.value}</dd>
          </div>
        ))}
      </dl>
      <p className="text-sm text-muted-foreground">
        Retention counts the first answer per card per local calendar day ({stats.retentionAttempts}{" "}
        attempts); Again fails, Hard/Good/Easy pass. Study time includes only {stats.timedReviews}{" "}
        reviews with recorded timing. {stats.overdue} overdue cards are counted separately from
        future due dates.
      </p>
      <p>
        {stats.newCards} new · {stats.learningCards} learning · {stats.reviewCards} review ·{" "}
        {stats.suspendedCards} suspended
      </p>
      <StatisticsBars
        title="Upcoming due dates · next 30 days"
        rows={stats.forecast.map((day) => ({ label: day.label, count: day.count }))}
      />
      <p className="text-sm text-muted-foreground">
        The forecast shows existing scheduled dates, excluding new and suspended cards. It does not
        predict future failures, new introductions, or reviews generated by completing these
        reviews.
      </p>
      <StatisticsBars
        title="Recorded study time · minutes"
        rows={stats.calendar.map((day) => ({
          label: day.label,
          count: Math.round(day.elapsedMs / 600) / 100,
        }))}
      />
      <StatisticsBars
        title="Review activity"
        rows={stats.calendar.map((day) => ({ label: day.label, count: day.reviews }))}
      />
      <div className="grid gap-5 sm:grid-cols-2">
        <StatisticsBars title="Review intervals · days" rows={stats.intervals} />
        <StatisticsBars title="Memory stability · days" rows={stats.stability} />
        <StatisticsBars title="Difficulty" rows={stats.difficulty} />
        <StatisticsBars title="Estimated recall · percent" rows={stats.retrievability} />
      </div>
    </section>
  );
}
function StatisticsBars({
  title,
  rows,
}: {
  readonly title: string;
  readonly rows: readonly { readonly label: string; readonly count: number }[];
}) {
  const maximum = Math.max(1, ...rows.map((row) => row.count));
  const width = Math.max(1, 720 / Math.max(1, rows.length));
  const valueRows = rows.map((row) => (
    <div key={row.label} className="flex justify-between gap-2">
      <dt>{row.label}</dt>
      <dd>{row.count}</dd>
    </div>
  ));
  return (
    <section className="min-w-0">
      <h3 className="mb-2 font-medium">{title}</h3>
      <p className="mb-1 text-xs text-muted-foreground">
        {rows.some((row) => row.count > 0)
          ? `Highest value: ${String(Math.max(0, ...rows.map((row) => row.count)))}`
          : "No recorded values in this range."}
      </p>
      <svg
        viewBox="0 0 720 140"
        role="img"
        aria-label={`${title}: ${String(rows.reduce((sum, row) => sum + row.count, 0))} total`}
        className="w-full overflow-visible border-b"
      >
        <line x1={0} y1={130} x2={720} y2={130} stroke="currentColor" opacity={0.2} />
        {rows.map((row, index) => (
          <rect
            key={row.label}
            x={index * width}
            y={130 - (row.count / maximum) * 120}
            width={Math.max(0.5, width - 2)}
            height={(row.count / maximum) * 120}
            fill="currentColor"
            className="text-primary"
          >
            <title>
              {row.label}: {row.count}
            </title>
          </rect>
        ))}
      </svg>
      <div className="mt-1 flex justify-between text-xs text-muted-foreground" aria-hidden="true">
        <span>{rows[0]?.label}</span>
        <span>{rows.at(-1)?.label}</span>
      </div>
      <Accordion type="single" collapsible>
        <AccordionItem value="values">
          <AccordionTrigger>View values</AccordionTrigger>
          <AccordionContent>
            <dl className="grid max-h-48 grid-cols-2 gap-2 overflow-y-auto text-sm">{valueRows}</dl>
          </AccordionContent>
        </AccordionItem>
      </Accordion>
    </section>
  );
}
