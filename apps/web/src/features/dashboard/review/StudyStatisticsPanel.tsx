import { InsightsSection } from "./InsightsSection";
import { StudyDistributions } from "./StudyDistributions";
import { StudyMemoryDetails } from "./StudyMemoryDetails";
import { StudyPlanner } from "./StudyPlanner";
import { useState } from "react";
import type { Workspace } from "@recall/domain";
import { studyCalendar, studyStatistics } from "@recall/application";
import {
  Select,
  SelectContent,
  SelectItem,
  SelectTrigger,
  SelectValue,
} from "@recall/ui-web/components/select";
import { Accordion } from "@recall/ui-web/components/accordion";

import { StatisticsBars } from "./StatisticsBars";

export function StudyStatisticsPanel({
  workspace,
  now,
}: {
  readonly workspace: Workspace;
  readonly now: number;
}) {
  const [scope, setScope] = useState("all");
  const [days, setDays] = useState("30");
  const stats = studyStatistics(
    workspace,
    now,
    studyCalendar(now, Number(days), 30, workspace.schedulerSettings?.studyDayStartHour),
    scope === "all" ? undefined : scope,
  );
  return (
    <section className="flex w-full min-w-0 max-w-4xl flex-col gap-6" aria-label="Study progress">
      <div className="flex flex-col gap-4 sm:flex-row">
        <Select value={scope} onValueChange={setScope}>
          <SelectTrigger
            size="lg"
            className="w-full min-w-0 sm:flex-1"
            aria-label="Statistics subject"
          >
            <SelectValue />
          </SelectTrigger>
          <SelectContent>
            <SelectItem value="all">All subjects</SelectItem>
            {workspace.areas.map((area) => (
              <SelectItem key={area.id} value={area.id}>
                {area.title}
              </SelectItem>
            ))}
          </SelectContent>
        </Select>
        <Select value={days} onValueChange={setDays}>
          <SelectTrigger
            size="lg"
            className="w-full min-w-0 sm:flex-1"
            aria-label="Statistics history"
          >
            <SelectValue />
          </SelectTrigger>
          <SelectContent>
            {[7, 30, 90, 365].map((value) => (
              <SelectItem key={value} value={String(value)}>
                Last {value} days
              </SelectItem>
            ))}
          </SelectContent>
        </Select>
      </div>
      <StatisticsBars
        title="Review activity"
        rows={stats.calendar.map((day) => ({ label: day.label, count: day.reviews }))}
      />
      <section
        className="flex flex-col gap-2 border-t border-border pt-6"
        aria-labelledby="recall-success-title"
      >
        <h2 id="recall-success-title" className="text-lg font-semibold">
          Recall success
        </h2>
        <p className="text-2xl font-semibold tabular-nums">
          {stats.trueRetention === null
            ? "No attempts yet"
            : `${(stats.trueRetention * 100).toFixed(0)}%`}
        </p>
        <p className="text-sm text-muted-foreground">
          {stats.calendar.reduce((sum, day) => sum + day.retentionPasses, 0)} successful recalls
          from {stats.retentionAttempts} first daily attempts. Again counts as a miss; Hard, Good
          and Easy count as successful recalls.
        </p>
      </section>
      <section className="flex flex-col gap-2" aria-label="Upcoming review forecast">
        <StatisticsBars
          title="Upcoming reviews"
          description="Next 7 days"
          emptyMessage="No cards are scheduled in the next 7 days."
          rows={stats.forecast.slice(0, 7).map((day) => ({ label: day.label, count: day.count }))}
        />
        <p className="max-w-prose text-sm text-muted-foreground">
          Scheduled cards only, separate from the history filter. Excludes {stats.overdue} overdue
          cards, new cards and reviews generated by future study.
        </p>
      </section>
      <Accordion type="multiple" className="flex flex-col gap-4">
        <InsightsSection
          value="details"
          title="Memory and study"
          description="Estimated memory, recorded study time and scheduled cards."
        >
          <StudyMemoryDetails stats={stats} />
        </InsightsSection>
        <InsightsSection
          value="distributions"
          title="Card distributions"
          description="How your cards vary in interval, stability, difficulty and recall."
        >
          <StudyDistributions stats={stats} />
        </InsightsSection>
        <InsightsSection
          value="simulator"
          title="Workload simulator"
          description="Compare study targets and estimated daily workload."
        >
          <StudyPlanner
            workspace={workspace}
            now={now}
            areaId={scope === "all" ? undefined : scope}
          />
        </InsightsSection>
      </Accordion>
    </section>
  );
}
