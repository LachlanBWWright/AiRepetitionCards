from datetime import datetime, timedelta, timezone
import math
from pathlib import Path
from fsrs import Card, Rating, Scheduler

initial = datetime(2026, 1, 1, 12, tzinfo=timezone.utc)
defaults = Scheduler(enable_fuzzing=False)
# Serialized fitted parameter IDs quantize weights to three decimal places.
scheduler = Scheduler(parameters=[math.floor(weight * 1000 + 0.5) / 1000 for weight in defaults.parameters], enable_fuzzing=False)
replay = Card(due=initial)
card = Card(due=initial)
losses = []
errors = []
for index in range(125):
    at = initial + timedelta(days=index)
    rating = Rating.Again if index % 5 == 0 else Rating.Good
    if index >= 100:
        probability = min(0.999, max(0.001, scheduler.get_card_retrievability(card, at)))
        outcome = 0 if rating == Rating.Again else 1
        losses.append(-math.log(probability if outcome else 1 - probability))
        errors.append((probability - outcome) ** 2)
    card, _ = scheduler.review_card(card, rating, at)
    replay, _ = defaults.review_card(replay, rating, at)

result = (
    '// Generated by generate-fsrs-reference.py using official fsrs==6.3.0.\n'
    '// This checks prediction/scoring compatibility, not optimizer convergence.\n'
    'export const pythonFsrsReference = {\n'
    f'  holdoutLoss: {sum(losses) / len(losses)!r},\n'
    f'  holdoutRmse: {math.sqrt(sum(errors) / len(errors))!r},\n'
    f'  finalStability: {replay.stability!r},\n'
    f'  finalDifficulty: {replay.difficulty!r},\n'
    '} as const;\n'
)
Path('packages/verification/tests/review/fsrs-reference-fixture.ts').write_text(result)
