"""Independent synthetic optimizer benchmark; run from the repository root.

Use Python 3.12 and fsrs[optimizer]==6.3.0, torch==2.14.1+cpu,
pandas==3.1.0, tqdm==4.66.5. The generated manifest records actual versions.
No real user history is included and this does not establish Anki optimizer parity.
"""
from datetime import datetime, timedelta, timezone
from importlib.metadata import version
import json
import math
from pathlib import Path
from fsrs import Card, Rating, ReviewLog, Scheduler
from fsrs.optimizer import Optimizer
import torch

# Fixed seed, CPU, float64 and single-threaded deterministic optimization.
torch.manual_seed(42)
torch.set_num_threads(1)
torch.use_deterministic_algorithms(True)
initial = datetime(2026, 1, 1, 12, tzinfo=timezone.utc)
logs = []
for card_index in range(24):
    profile = card_index % 3
    for index in range(40):
        at = initial + timedelta(days=index * (profile + 1), minutes=card_index)
        choice = (card_index * 17 + index * 11) % 20
        failure = [8, 4, 1][profile]
        rating = (Rating.Again if choice < failure else Rating.Hard if choice == 9
                  else Rating.Easy if choice == 19 else Rating.Good)
        logs.append(ReviewLog(card_id=card_index, rating=rating,
                              review_datetime=at, review_duration=None))
logs.sort(key=lambda log: (log.review_datetime, log.card_id))
cutoff = logs[math.floor(len(logs) * 0.8)].review_datetime
training = [log for log in logs if log.review_datetime < cutoff]
weights = Optimizer(training).compute_optimal_parameters()
weights = [math.floor(weight * 1000 + 0.5) / 1000 for weight in weights]
scheduler = Scheduler(parameters=weights, enable_fuzzing=False)
cards = {}
losses = []
errors = []
for log in logs:
    card = cards.get(log.card_id, Card(card_id=log.card_id, due=log.review_datetime))
    if log.review_datetime >= cutoff and card.last_review:
        probability = min(0.999, max(0.001, scheduler.get_card_retrievability(card, log.review_datetime)))
        outcome = 0 if log.rating == Rating.Again else 1
        losses.append(-math.log(probability if outcome else 1 - probability))
        errors.append((probability - outcome) ** 2)
    first_review = card.last_review is None
    cards[log.card_id], _ = scheduler.review_card(card, log.rating, log.review_datetime)
    # ts-fsrs 5.4.2 enforces a 0.1-day initial stability floor; py-fsrs permits 0.001.
    # Keep optimization independent; apply this floor only to first-answer scoring.
    if first_review:
        cards[log.card_id].stability = max(0.1, cards[log.card_id].stability)

manifest = {
    "referenceName": "Official py-fsrs 6.3.0 optimizer; deterministic synthetic mixed profiles",
    "packages": {name: version(name) for name in ["fsrs", "torch", "pandas", "tqdm"]},
    "seed": 42,
    "scoringMinimumInitialStability": 0.1,
    "cards": 24,
    "reviews": len(logs),
    "trainingReviews": len(training),
    "holdoutStartsAt": cutoff.isoformat().replace("+00:00", "Z"),
    "holdoutObservations": len(losses),
    "referenceWeights": weights,
    "holdoutLogLoss": sum(losses) / len(losses),
    "holdoutRmse": math.sqrt(sum(errors) / len(errors)),
}
output = Path("packages/verification/tests/review/optimizer-reference-fixture.ts")
output.write_text("// Generated by generate-optimizer-reference.py. Synthetic, independently optimized reference.\n"
                  + "export const optimizerReference = " + json.dumps(manifest, indent=2) + " as const;\n")
print(json.dumps(manifest, indent=2))
